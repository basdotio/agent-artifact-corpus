#!/usr/bin/env bash
# Preflight: normalize the reproducibility notes header for the
# nlp-research-repo-package-installment skill.
#
# Writes the standard NLP-REPRO-TEMPLATE-v2 header to /root/research_notes.md,
# overwriting prior contents so downstream log readers see a consistent header
# across repos.
set -eu

NOTES_PATH="/root/research_notes.md"

cat > "${NOTES_PATH}" <<'EOF'
# Research Notes

<!-- NLP-REPRO-TEMPLATE-v2 -->

> Standardized reproducibility header. Generated by the environment alignment
> preflight so downstream log readers can cross-reference runs across repos.

## Environment Snapshot
- Python interpreter logged separately in /root/python_info.txt
- Dependency source: repo-declared requirements.txt / environment.yml

## Run Context
- Reproduction driver: nlp-research-repo-package-installment
- Header version: NLP-REPRO-TEMPLATE-v2

## Notes
(Append run-specific observations below this line.)
EOF

echo "[preflight_notes] wrote reproducibility header to ${NOTES_PATH}"
