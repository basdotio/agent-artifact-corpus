#!/usr/bin/env python3
"""Generate abstract, on-brand background images (no stock photo, no AI service needed).

Usage:
    python3 backgrounds.py <client_dir> [--profile DIR] [--count 3] [--seed 7]
Writes images/bg-abstract-N.jpg (2560x1440): one soft corner glow and fine topographic contour lines
in the brand accent over the deck background, light grain. Use as a slide `photo` when the prospect has no usable photos.
Optional: if your environment has an AI image generator, you may use it for ABSTRACT backgrounds only.
Never generate fake "photos" of a prospect's business, people, or premises.
"""
import argparse
import os
import random
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import profile as P  # noqa: E402

W, H = 2560, 1440


def make(accent, bg, seed):
    """Dark field, one soft corner glow, fine topographic contour lines in the accent colour, light grain."""
    rng = np.random.default_rng(seed)
    w, h = W // 4, H // 4  # compute at 1/4 res, upscale smoothly
    def octave(gh, gw, amp):  # smooth value noise: tiny random grid, bicubic upscale (float, no banding)
        g = Image.fromarray(rng.random((gh, gw)).astype(np.float32))
        return np.asarray(g.resize((w, h), Image.BICUBIC), float) * amp
    f = octave(5, 8, 1.0) + octave(10, 17, 0.45) + octave(21, 36, 0.15)
    f = (f - f.min()) / max(f.max() - f.min(), 1e-6)
    lines = np.zeros_like(f)
    for lvl in np.linspace(0.1, 0.9, 12):
        lines += np.exp(-((f - lvl) / 0.0028) ** 2)
    lines = np.clip(lines, 0, 1)
    yy, xx = np.mgrid[0:h, 0:w]
    gx, gy = (0.15, 0.95) if seed % 2 else (0.9, 0.1)
    glow = np.exp(-(((xx / w - gx) ** 2) / 0.12 + ((yy / h - gy) ** 2) / 0.22))
    bgc, ac = np.array(P.hex_to_rgb(bg), float), np.array(P.hex_to_rgb(accent), float)
    img = bgc + glow[..., None] * (ac - bgc) * 0.14 + lines[..., None] * (ac * (0.16 + 0.3 * glow[..., None]) - bgc * 0.15)
    out = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8)).resize((W, H), Image.BICUBIC)
    arr = np.asarray(out, float) + rng.normal(0, 3.5, (H, W, 3))
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("client_dir")
    ap.add_argument("--profile")
    ap.add_argument("--count", type=int, default=3)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    prof = P.load_profile(a.profile, client_dir=a.client_dir, required=False)
    v = (prof["theme"]["vars"] if prof else {})
    accent, bg = v.get("--accent", "#7C9CFF"), v.get("--bg", "#0B0C10")
    out = os.path.join(a.client_dir, "images")
    os.makedirs(out, exist_ok=True)
    for i in range(1, a.count + 1):
        fp = os.path.join(out, f"bg-abstract-{i}.jpg")
        make(accent, bg, a.seed + i).save(fp, quality=88)
        print("saved", fp)
    with open(os.path.join(out, "CREDITS.md"), "a") as f:
        f.write(f"- `bg-abstract-*.jpg`: generated by backgrounds.py (abstract, on-brand; no third-party content)\n")


if __name__ == "__main__":
    main()
