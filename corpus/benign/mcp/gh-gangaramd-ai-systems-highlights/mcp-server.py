"""MCP server Lambda for the shop database — FastMCP @mcp.tool() approach.

@mcp.tool() is the decorator that turns any Python function into an MCP tool.
FastMCP auto-generates the JSON Schema from type hints and docstrings — no schema
defined in Terraform, no property blocks, no manual JSON.

Compare with ../lambda_src/db_query.py (the inline approach):
  Inline:  Lambda is a plain function  →  Gateway wraps it in MCP,
           schemas declared in Terraform property blocks.
  Here:    Lambda IS the MCP server   →  handles tools/list + tools/call directly,
           schemas auto-generated by FastMCP from type hints + docstrings below.

The ASGI HTTP server (streamable_http_app + Mangum) is bypassed: we call FastMCP's
tool dispatch (mcp.list_tools / mcp.call_tool) directly from a plain Lambda handler.
Same @mcp.tool() decorator, same auto-generated schemas — no Host-header or task-group
issues that come from running a full ASGI stack on Lambda.
"""
import asyncio
import base64
import json
import os

import boto3
from mcp.server.fastmcp import FastMCP

CLUSTER_ARN = os.environ["CLUSTER_ARN"]
SECRET_ARN  = os.environ["SECRET_ARN"]
DB_NAME     = os.environ["DB_NAME"]

rds = boto3.client("rds-data")
mcp = FastMCP("ShopMCP")


# ---- Data API helpers -------------------------------------------------------

def _execute(sql: str, params=None) -> dict:
    return rds.execute_statement(
        resourceArn=CLUSTER_ARN,
        secretArn=SECRET_ARN,
        database=DB_NAME,
        sql=sql,
        includeResultMetadata=True,
        parameters=params or [],
    )


def _rows(resp) -> list[dict]:
    cols = [c["name"] for c in resp.get("columnMetadata", [])]
    return [
        dict(zip(cols, [
            None if f.get("isNull") else next(iter(f.values()))
            for f in record
        ]))
        for record in resp.get("records", [])
    ]


# ---- MCP tools: @mcp.tool() auto-generates JSON Schema from type hints ------

@mcp.tool()
def list_tables() -> list[str]:
    """List all tables in the shop database."""
    try:
        sql = ("SELECT table_name FROM information_schema.tables "
               "WHERE table_schema='public' ORDER BY table_name")
        return [r["table_name"] for r in _rows(_execute(sql))]
    except Exception as e:
        return [f"error: {e}"]


@mcp.tool()
def describe_table(table: str) -> dict:
    """Get column names and data types for one table.

    Args:
        table: Name of the table to describe, e.g. 'orders'
    """
    try:
        sql = ("SELECT column_name, data_type FROM information_schema.columns "
               "WHERE table_schema='public' AND table_name = :t ORDER BY ordinal_position")
        rows = _rows(_execute(sql, [{"name": "t", "value": {"stringValue": table}}]))
        if not rows:
            return {"error": f"Table '{table}' not found. Call list_tables to see available tables."}
        return {"table": table, "columns": rows}
    except Exception as e:
        return {"error": str(e)}


@mcp.tool()
def run_select(sql: str) -> dict:
    """Execute a read-only SQL SELECT query against the shop database.

    The shop schema:
      customers(id, name, city)
      products(id, name, price_usd, in_stock)
      orders(id, customer_id, product_id, quantity, status, ordered_on)

    For order totals: JOIN orders with products on product_id=id and multiply
    price_usd * quantity. For customer names: JOIN with customers on customer_id=id.

    Args:
        sql: A SELECT statement, e.g. 'SELECT * FROM orders ORDER BY id DESC LIMIT 5'
    """
    try:
        sql = sql.strip().rstrip(";")
        if not sql.lower().startswith("select"):
            return {"error": "Only SELECT statements are allowed."}
        if ";" in sql:
            return {"error": "Only a single statement is allowed."}
        if " limit " not in sql.lower():
            sql += " LIMIT 100"
        return {"rows": _rows(_execute(sql))}
    except Exception as e:
        return {"error": f"SQL error: {e}. Use describe_table to check column names."}


# ---- MCP JSON-RPC dispatch --------------------------------------------------

def _ok(req_id, result):
    return {"jsonrpc": "2.0", "id": req_id, "result": result}


def _err(req_id, code, message):
    return {"jsonrpc": "2.0", "id": req_id, "error": {"code": code, "message": message}}


async def _dispatch(req: dict) -> dict | None:
    method = req.get("method", "")
    req_id = req.get("id")
    params = req.get("params") or {}

    if method == "initialize":
        # Echo the client's requested version back — the Gateway will reject
        # any version it doesn't recognise, so this keeps the handshake open.
        version = params.get("protocolVersion", "2025-03-26")
        return _ok(req_id, {
            "protocolVersion": version,
            "capabilities": {"tools": {}},
            "serverInfo": {"name": "ShopMCP", "version": "1.0.0"},
        })

    if method in ("notifications/initialized", "initialized"):
        return None  # notification — no response needed

    if method == "ping":
        return _ok(req_id, {})

    if method == "tools/list":
        # FastMCP reads type hints + docstrings to build the schema automatically
        tools = await mcp.list_tools()
        return _ok(req_id, {
            "tools": [
                {"name": t.name, "description": t.description or "", "inputSchema": t.inputSchema}
                for t in tools
            ]
        })

    if method == "tools/call":
        name = params.get("name", "")
        args = params.get("arguments") or {}
        result = await mcp.call_tool(name, args)
        # FastMCP returns list of TextContent / ImageContent items
        content = [item.model_dump() for item in result]
        return _ok(req_id, {"content": content})

    return _err(req_id, -32601, f"Method not found: {method}")


# ---- Lambda entry point -----------------------------------------------------

def handler(event, context):
    body = event.get("body") or "{}"
    if event.get("isBase64Encoded"):
        body = base64.b64decode(body).decode()

    try:
        req = json.loads(body)
    except json.JSONDecodeError:
        return {"statusCode": 400, "headers": {"Content-Type": "application/json"},
                "body": json.dumps(_err(None, -32700, "Parse error"))}

    response = asyncio.run(_dispatch(req))
    if response is None:
        return {"statusCode": 202, "body": ""}

    return {"statusCode": 200, "headers": {"Content-Type": "application/json"},
            "body": json.dumps(response)}
