"""``mcp-forge doctor``: run a protocol check-up against any MCP server.

The checks are the ones that actually break servers in the wild: a handshake
that never answers, ``print()`` polluting stdout, tool names a client will
reject, missing descriptions, and crashes on unknown methods or bad JSON.

It works against *any* stdio MCP server, not only ones generated by
mcp-forge -- point it at a command and read the report.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import dataclass
from typing import Any

from .client import ProtocolError, StdioClient

__all__ = ["Check", "run_checks", "format_report"]

NAME_PATTERN = re.compile(r"^[A-Za-z0-9_.-]{1,64}$")
KNOWN_VERSIONS = {"2025-06-18", "2025-03-26", "2024-11-05"}


@dataclass
class Check:
    name: str
    status: str  # "pass" | "warn" | "fail"
    detail: str = ""

    @property
    def icon(self) -> str:
        return {"pass": "PASS", "warn": "WARN", "fail": "FAIL"}[self.status]


def run_checks(command: list[str], *, cwd: str | None = None,
               env: dict[str, str] | None = None, timeout: float = 20.0) -> list[Check]:
    checks: list[Check] = []
    try:
        client = StdioClient(command, cwd=cwd, env=env, timeout=timeout)
    except FileNotFoundError:
        return [Check("launch", "fail", f"cannot execute {command[0]!r}")]

    with client:
        # 1. handshake -------------------------------------------------
        try:
            info = client.initialize()
        except (ProtocolError, json.JSONDecodeError) as exc:
            checks.append(Check("initialize", "fail", str(exc)))
            return checks
        checks.append(Check("initialize", "pass", "handshake answered"))

        version = info.get("protocolVersion")
        if version in KNOWN_VERSIONS:
            checks.append(Check("protocolVersion", "pass", str(version)))
        else:
            checks.append(Check("protocolVersion", "fail",
                                f"{version!r} is not a published MCP revision"))

        server_info = info.get("serverInfo") or {}
        if server_info.get("name") and server_info.get("version"):
            checks.append(Check("serverInfo", "pass",
                                f"{server_info['name']} v{server_info['version']}"))
        else:
            checks.append(Check("serverInfo", "fail", "name and version are required"))

        capabilities = info.get("capabilities") or {}
        if "tools" in capabilities:
            checks.append(Check("capabilities.tools", "pass", "declared"))
        else:
            checks.append(Check("capabilities.tools", "warn",
                                "no tools capability declared; clients may hide your tools"))

        # 2. ping ------------------------------------------------------
        try:
            client.send("ping")
            checks.append(Check("ping", "pass", "answered"))
        except ProtocolError as exc:
            checks.append(Check("ping", "warn", str(exc)))

        # 3. tools/list ------------------------------------------------
        try:
            tools = client.list_tools()
        except ProtocolError as exc:
            checks.append(Check("tools/list", "fail", str(exc)))
            return checks
        checks.append(Check("tools/list", "pass", f"{len(tools)} tool(s)"))
        checks.extend(_check_tools(tools))

        # 4. robustness -------------------------------------------------
        raw = client.send_raw({"jsonrpc": "2.0", "id": 9001, "method": "does/not/exist"})
        code = (raw.get("error") or {}).get("code")
        if code == -32601:
            checks.append(Check("unknown method", "pass", "returns -32601"))
        else:
            checks.append(Check("unknown method", "warn",
                                f"expected -32601, got {code!r}"))

        raw = client.send_raw({"jsonrpc": "2.0", "id": 9002, "method": "tools/call",
                               "params": {"name": "__nope__", "arguments": {}}})
        if "error" in raw or (raw.get("result") or {}).get("isError"):
            checks.append(Check("unknown tool", "pass", "rejected cleanly"))
        else:
            checks.append(Check("unknown tool", "fail", "accepted a tool that does not exist"))

        try:
            raw = client.send_text("{ this is not json }")
            code = (raw.get("error") or {}).get("code")
            checks.append(Check("malformed JSON", "pass" if code == -32700 else "warn",
                                "returns -32700" if code == -32700
                                else f"expected -32700, got {code!r}"))
            client.send("ping")
            checks.append(Check("survives traffic", "pass",
                                "still answering after bad input"))
        except ProtocolError as exc:
            checks.append(Check("survives traffic", "fail", str(exc)))

        if client.noise:
            checks.append(Check("stdout purity", "fail",
                                f"non-JSON line(s) on stdout, e.g. {client.noise[0][:60]!r}; "
                                "logs must go to stderr"))
        else:
            checks.append(Check("stdout purity", "pass", "only JSON-RPC on stdout"))

    return checks


def _check_tools(tools: list[dict[str, Any]]) -> list[Check]:
    checks: list[Check] = []
    if not tools:
        return [Check("tool specs", "warn", "the server exposes no tools")]

    bad_names = [t.get("name") for t in tools
                 if not isinstance(t.get("name"), str) or not NAME_PATTERN.match(t["name"])]
    counts = Counter(t.get("name") for t in tools)
    duplicates = [name for name, times in counts.items() if times > 1]
    missing_doc = [t.get("name") for t in tools if not (t.get("description") or "").strip()]
    bad_schema = [t.get("name") for t in tools
                  if not isinstance(t.get("inputSchema"), dict)
                  or t["inputSchema"].get("type") != "object"]

    checks.append(Check("tool names", "fail" if bad_names else "pass",
                        f"invalid: {bad_names}" if bad_names else "all match [A-Za-z0-9_.-]{1,64}"))
    if duplicates:
        checks.append(Check("tool uniqueness", "fail", f"duplicated: {duplicates}"))
    checks.append(Check("inputSchema", "fail" if bad_schema else "pass",
                        f"not an object schema: {bad_schema}" if bad_schema
                        else "every tool declares an object schema"))
    checks.append(Check("descriptions", "warn" if missing_doc else "pass",
                        f"empty for: {missing_doc}" if missing_doc
                        else "every tool is documented"))
    return checks


def format_report(command: list[str], checks: list[Check]) -> str:
    width = max((len(c.name) for c in checks), default=10)
    lines = [f"mcp-forge doctor -> {' '.join(command)}", ""]
    for check in checks:
        lines.append(f"  [{check.icon}] {check.name.ljust(width)}  {check.detail}")
    failed = sum(1 for c in checks if c.status == "fail")
    warned = sum(1 for c in checks if c.status == "warn")
    passed = sum(1 for c in checks if c.status == "pass")
    lines += ["", f"  {passed} passed, {warned} warnings, {failed} failures"]
    return "\n".join(lines)
