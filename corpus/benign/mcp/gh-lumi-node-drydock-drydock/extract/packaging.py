"""Generate packaging metadata for extracted components.

Produces build files (pyproject.toml, Cargo.toml, go.mod, package.json) and
.gitignore, so the extracted component stands alone as a publishable package.
"""

from __future__ import annotations

from .models import ExtractionPlan

__all__ = ["generate_packaging"]


def generate_packaging(plan: ExtractionPlan) -> dict[str, str]:
    """Generate packaging files for the extracted component.

    Returns {relative_path: file_contents} to be written into the extraction.

    Never overwrites files that are already in plan.files destinations.
    Generated files are per-language build metadata plus .gitignore.
    """
    output: dict[str, str] = {}

    # Check which destinations are already occupied to avoid clobbering.
    occupied_dests = {f.destination for f in plan.files}

    # Generate language-specific build files.
    if "python" in plan.languages and "pyproject.toml" not in occupied_dests:
        output["pyproject.toml"] = _generate_pyproject(plan)

    if "rust" in plan.languages and "Cargo.toml" not in occupied_dests:
        output["Cargo.toml"] = _generate_cargo(plan)

    if "go" in plan.languages and "go.mod" not in occupied_dests:
        output["go.mod"] = _generate_gomod(plan)

    if ("javascript" in plan.languages or "typescript" in plan.languages) and \
            "package.json" not in occupied_dests:
        output["package.json"] = _generate_package_json(plan)

    # Always generate .gitignore (unless already present, which is rare but possible).
    if ".gitignore" not in occupied_dests:
        output[".gitignore"] = _generate_gitignore(plan)

    return output


def _escape_toml_string(s: str) -> str:
    """Escape a string for TOML (basic literal-only escaping)."""
    # TOML strings need " and \ escaped; backslash must come first.
    s = s.replace("\\", "\\\\")
    s = s.replace('"', '\\"')
    return s


def _generate_pyproject(plan: ExtractionPlan) -> str:
    """Generate pyproject.toml for Python component."""
    # Normalize component name for Python package naming.
    pkg_name = plan.component.replace("_", "-").lower()

    lines = [
        "[build-system]",
        'requires = ["hatchling"]',
        'build-backend = "hatchling.build"',
        "",
        "[project]",
        f'name = "{pkg_name}"',
        'version = "0.1.0"',
        f'description = "Extracted component from {plan.project}"',
        'requires-python = ">=3.10"',
    ]

    # External dependencies.
    py_deps = sorted(plan.external_deps.get("python", []))
    if py_deps:
        lines.append('dependencies = [')
        for dep in py_deps:
            lines.append(f'    "{_escape_toml_string(dep)}",')
        lines.append(']')

    # Name the wheel contents explicitly rather than relying on hatchling's
    # directory-name heuristic. The heuristic looks for a directory matching the
    # *normalised* project name, so any component whose name contains an
    # underscore (langs_pack -> langs-pack) fails to build with a confusing
    # "unable to determine which files to ship" error.
    lines.extend([
        "",
        "[tool.hatch.build.targets.wheel]",
        f'packages = ["{_escape_toml_string(plan.component)}"]',
    ])

    # Footer with generation note.
    lines.extend([
        "",
        "# Generated by Drydock extraction from:",
        f'# Project: {plan.project}',
        f'# Source: {plan.source_root}',
        f'# Commit: {plan.source_commit or "unknown"}',
        "#",
        "# TODO(human): dependency versions are unpinned and the licence is unset.",
    ])

    return "\n".join(lines) + "\n"


def _generate_cargo(plan: ExtractionPlan) -> str:
    """Generate Cargo.toml for Rust component."""
    crate_name = plan.component.replace("-", "_")

    lines = [
        "[package]",
        f'name = "{plan.component}"',
        'version = "0.1.0"',
        'edition = "2021"',
        f'description = "Extracted component from {plan.project}"',
    ]

    # External dependencies (version * with a note to pin).
    rust_deps = sorted(plan.external_deps.get("rust", []))
    if rust_deps:
        lines.append("")
        lines.append("[dependencies]")
        for dep in rust_deps:
            # Extract crate name (before any operators).
            crate = dep.split(" ")[0].split("@")[0]
            lines.append(f'{crate} = "*"  # FIXME: pin to a specific version')

    lines.extend([
        "",
        "# Generated by Drydock extraction from:",
        f'# Project: {plan.project}',
        f'# Source: {plan.source_root}',
        f'# Commit: {plan.source_commit or "unknown"}',
    ])

    return "\n".join(lines) + "\n"


def _generate_gomod(plan: ExtractionPlan) -> str:
    """Generate go.mod for Go component."""
    lines = [
        f"module {plan.component}",
        "",
        "go 1.21",
    ]

    # External dependencies.
    go_deps = sorted(plan.external_deps.get("go", []))
    if go_deps:
        lines.append("")
        lines.append("require (")
        for dep in go_deps:
            # Format: github.com/user/repo or similar
            lines.append(f"    {dep} v0.0.0  // version to be pinned")
        lines.append(")")

    lines.extend([
        "",
        "// Generated by Drydock extraction from:",
        f"// Project: {plan.project}",
        f"// Source: {plan.source_root}",
        f"// Commit: {plan.source_commit or 'unknown'}",
    ])

    return "\n".join(lines) + "\n"


def _generate_package_json(plan: ExtractionPlan) -> str:
    """Generate package.json for a JavaScript/TypeScript component.

    Built with `json.dumps` rather than assembled as text. An earlier version
    appended ``// FIXME`` comments after dependency entries to flag unpinned
    versions -- honest, but JSON has no comments, so npm rejected the file
    outright. The caveats now live in a `_drydock` metadata key, which is valid
    JSON and survives a round-trip through any tool that reads the manifest.
    """
    import json

    pkg_name = plan.component.replace("_", "-").lower()

    deps = sorted(
        set(plan.external_deps.get("javascript", []))
        | set(plan.external_deps.get("typescript", []))
    )

    manifest: dict[str, object] = {
        "name": pkg_name,
        "version": "0.1.0",
        "type": "module",
        "description": f"Extracted component from {plan.project}",
        "dependencies": {d: "*" for d in deps},
        "_drydock": {
            "generated_by": "drydock extract",
            "source_project": plan.project,
            "source_root": plan.source_root,
            "source_commit": plan.source_commit or "unknown",
            "todo": [
                "Dependency versions are unpinned ('*'); pin them before publishing.",
                "No license field is set; choose one.",
            ],
        },
    }

    return json.dumps(manifest, indent=2, sort_keys=False) + "\n"


