def correlation(value=None):
    # Opaque random IDs only: never persist arbitrary caller strings.
    return (
        value
        if isinstance(value, str) and re.fullmatch(r"[0-9a-f]{32}", value)
        else uuid.uuid4().hex
    )


def reason(value):
    return value if isinstance(value, str) and value in REASONS else "unknown"


def next_step(code):
    if code in NEXT_STEPS:
        return NEXT_STEPS[code]
    if code in ("playback_active", "playing", "playback_unknown"):
        return "Wait until viewing has finished and playback state is known."
    if code in ("profile_changed", "server_retired"):
        return "Reconnect to the active profile and inspect state before making changes."
    if code in REFUSALS:
        return "Review permissions, supported versions and the operation's preview before making changes."
    return "Inspect bounded diagnostics and current state before retrying; never automatically repeat a write."


def references(result):
    """Only opaque IDs generated by the existing backup components; no map keys."""
    found = {"backup_refs": [], "recovery_refs": []}
    if not isinstance(result, dict):
        return found
    for field, dest in (
        ("backup_id", "backup_refs"),
        ("undo_backup_id", "recovery_refs"),
        ("undo_backups", "recovery_refs"),
    ):
        values = result.get(field)
        values = list(values.values())[:20] if isinstance(values, dict) else [values]
        for value in values:
            if isinstance(value, str) and re.fullmatch(
                r"(?:[0-9a-f]{32}|[0-9]{8}-[0-9]{6}(?:-[0-9a-f]{1,32})?)", value
            ):
                if value not in found[dest]:
                    found[dest].append(value)
    return found


def capture_backup(backup_id):
    context = CONTEXT.get()
    if context is not None:
        context["backup_refs"] = list(
            dict.fromkeys(
                context["backup_refs"] + references({"backup_id": backup_id})["backup_refs"]
            )
        )[:20]


def record(operation, correlation_id, started, code="ok", outcome="succeeded", result=None):
    code = reason(code)
    operation = operation if re.fullmatch(r"[a-z][a-z0-9_]{0,79}", operation or "") else "unknown"
    return {
        "schema_version": VERSION,
        "operation_id": uuid.uuid4().hex,
        "correlation_id": correlation(correlation_id),
        "operation": operation,
        "decision": "refuse" if outcome == "refused" else "allow",
        "reason_code": code,
        "duration_ms": min(86400000, max(0, int((time.monotonic() - started) * 1000))),
        "outcome": outcome
        if outcome in ("succeeded", "refused", "failed", "partial", "unknown")
        else "unknown",
        "recorded_at": int(time.time()),
        **references(result),
    }


def clean(row):
    """Validate persisted/remote records and project strictly onto the v1 fields."""
    if not isinstance(row, dict) or row.get("schema_version") != VERSION:
        return None
    for key in ("operation_id", "correlation_id"):
        if not isinstance(row.get(key), str) or not re.fullmatch(r"[0-9a-f]{32}", row[key]):
            return None
    if not isinstance(row.get("operation"), str) or not re.fullmatch(
        r"[a-z][a-z0-9_]{0,79}", row["operation"]
    ):
        return None
    if not isinstance(row.get("reason_code"), str) or not isinstance(row.get("outcome"), str):
        return None
    if row.get("reason_code") not in REASONS or row.get("outcome") not in (
        "succeeded",
        "refused",
        "failed",
        "partial",
        "unknown",
    ):
        return None
    if not isinstance(row.get("decision"), str) or row.get("decision") not in ("allow", "refuse"):
        return None
    for key in ("duration_ms", "recorded_at"):
        if type(row.get(key)) is not int or not 0 <= row[key] <= 10**12:
            return None
    result = {
        key: row[key]
        for key in (
            "schema_version",
            "operation_id",
            "correlation_id",
            "operation",
            "decision",
            "reason_code",
            "duration_ms",
            "outcome",
            "recorded_at",
        )
    }
    for key in ("backup_refs", "recovery_refs"):
        values = row.get(key, [])
        if not isinstance(values, list):
            return None
        result[key] = references({"undo_backups": dict(enumerate(values[:20]))})["recovery_refs"]
    return result


class History:
    """Private, <=1 MiB database with <=256 metadata records, retained for seven days.

    A None path is an explicitly ephemeral store for demo/test backends.
    Failed persistence never changes the operation outcome and is reported separately.
    """

    def __init__(self, directory=None):
        self.directory = str(directory) if directory is not None else None
        self._rows = collections.deque(maxlen=MAX_RECORDS)
        self._lock = threading.RLock()
        self.available = True

    def _connect(self):
        if self.directory is None:
            raise OSError("History directory unavailable")
        os.makedirs(self.directory, mode=0o700, exist_ok=True)
        if os.path.islink(self.directory):
            raise OSError("Unsafe operation history directory")
        try:
            os.chmod(self.directory, 0o700)
        except OSError:  # Android shared storage refuses chmod; the islink checks still apply.
            pass
        path = os.path.join(self.directory, "history.sqlite3")
        if os.path.islink(path):
            raise OSError("Unsafe operation history file")
        if os.path.exists(path) and os.path.getsize(path) > 1048576:
            raise OSError("Operation history exceeds storage limit")
        fd = os.open(path, os.O_CREAT | os.O_RDWR, 0o600)
        os.close(fd)
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
        db = sqlite3.connect(path, timeout=1.0)
        try:
            db.execute("PRAGMA max_page_count=256")
            db.execute(
                "CREATE TABLE IF NOT EXISTS operations (id INTEGER PRIMARY KEY, at INTEGER, record TEXT)"
            )
            return db
        except Exception:
            db.close()
            raise

    def _retry(self, work):
        # Another process (Kodi Manager and nvidia-MCP, or a second Kodi profile) may hold the
        # write lock briefly, including while the table is created on connect; Windows reports
        # that sooner than POSIX. Retry busy/locked errors for at most about 2 s.
        attempts = 6
        for attempt in range(attempts):
            db = None
            try:
                db = self._connect()
                return work(db)
            except sqlite3.OperationalError as exc:
                busy = "locked" in str(exc) or "busy" in str(exc)
                if not busy or attempt == attempts - 1:
                    raise
            finally:
                if db is not None:
                    db.close()
            time.sleep(0.05 * (2**attempt))
        raise sqlite3.OperationalError("database is locked")

    def _append_shared(self, row):
        def work(db):
            with db:
                db.execute("BEGIN IMMEDIATE")
                db.execute(
                    "DELETE FROM operations WHERE at < ?",
                    (int(time.time()) - RETENTION,),
                )
                db.execute(
                    "DELETE FROM operations WHERE id NOT IN (SELECT id FROM operations ORDER BY id DESC LIMIT ?)",
                    (MAX_RECORDS - 1,),
                )
                db.execute(
                    "INSERT INTO operations (at, record) VALUES (?, ?)",
                    (row["recorded_at"], json.dumps(row, separators=(",", ":"))),
                )

        self._retry(work)

    def append(self, row):
        try:
            row = clean(row)
            if row is None:
                return False
            with self._lock:
                if self.directory is None:
                    self._rows.append(row)
                else:
                    self._append_shared(row)
            self.available = True
            return True
        except Exception:
            self.available = False
            return False

    def selected(self, limit=20):
        limit = min(MAX_SELECTED, max(1, int(limit)))
        try:
            with self._lock:
                if self.directory is None:
                    rows = list(reversed(self._rows))
                else:
                    rows = self._retry(
                        lambda db: [
                            json.loads(item[0])
                            for item in db.execute(
                                "SELECT record FROM operations WHERE at >= ? AND length(record) <= 4096 ORDER BY id DESC LIMIT ?",
                                (int(time.time()) - RETENTION, limit),
                            )
                        ]
                    )
            return [
                r
                for r in (clean(row) for row in rows)
                if r and r["recorded_at"] >= int(time.time()) - RETENTION
            ][:limit]
        except Exception:
            self.available = False
            return []

    def summary(self):
        rows = self.selected(MAX_SELECTED)
        return {
            "schema_version": VERSION,
            "history_available": self.available,
            "selected_count": len(rows),
            "max_records": MAX_RECORDS,
            "retention_days": 7,
            "outcomes": dict(collections.Counter(row["outcome"] for row in rows)),
            "reason_codes": dict(collections.Counter(row["reason_code"] for row in rows)),
        }


def safe_number(value):
    return (
        value
        if type(value) in (int, float) and abs(value) <= 10**12 and math.isfinite(value)
        else None
    )
